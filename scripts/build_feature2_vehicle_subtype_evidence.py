def as_nullable_int(frame: pd.DataFrame, column: str) -> None:
    frame[column] = pd.to_numeric(frame[column], errors="coerce").astype("Int64")


def main() -> None:
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    manifest_by_id = {row["source_id"]: row for row in manifest["documents"]}
    records: list[dict[str, Any]] = []
    accepted_statuses = {"verified_content", "verified_cached_content"}
    for seed in CURATED_INCIDENTS:
        source = manifest_by_id.get(seed["source_id"])
        if source is None or source.get("status") not in accepted_statuses:
            raise RuntimeError(f"Source is not a verified raw artifact: {seed['source_id']}")
        local_path = ROOT / source["local_path"]
        if not local_path.exists():
            raise RuntimeError(f"Raw artifact missing: {local_path}")
        content_sha = hashlib.sha256(local_path.read_bytes()).hexdigest()
        if content_sha != source["sha256"]:
            raise RuntimeError(f"Raw artifact hash mismatch: {seed['source_id']}")
        row = {key: value for key, value in seed.items() if key != "field_provenance"}
        row.update({
            "source_kind": source["kind"],
            "source_publisher": source["publisher"],
            "source_url": source["url"],
            "source_status": source["status"],
            "source_sha256": source["sha256"],
            "source_raw_artifact": source["local_path"],
            "source_text_artifact": source["local_text_path"],
            "source_field_provenance_json": json.dumps(seed["field_provenance"], ensure_ascii=False, sort_keys=True),
            "admission_scope": "supplementary_cross_kalimantan_vehicle_evidence",
            "eligible_for_kalteng_cohort_training": False,
            "permitted_feature2_use": "case-library evidence and future external validation only",
        })
        canonical = json.dumps(row, ensure_ascii=False, sort_keys=True, default=str)
        row["record_sha256"] = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
        records.append(row)

    frame = pd.DataFrame(records)
    nullable_counts = [
        "personnel_total", "personnel_known_lower_bound",
        "fire_engine_count_explicit_positive", "water_tanker_count_explicit_positive",
        "pickup_count_explicit_positive", "other_explicit_vehicle_count",
        "documented_vehicle_lower_bound",
    ]
    for column in nullable_counts:
        as_nullable_int(frame, column)
    for subtype in [
        "fire_engine_count_explicit_positive", "water_tanker_count_explicit_positive",
        "pickup_count_explicit_positive",
    ]:
        if frame[subtype].dropna().le(0).any():
            raise RuntimeError(f"{subtype} may contain positive observations only")

    frame = frame.sort_values("evidence_id").reset_index(drop=True)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    frame.to_parquet(OUTPUT_DIR / "feature2_vehicle_subtype_evidence.parquet", index=False)
    frame.to_csv(OUTPUT_DIR / "feature2_vehicle_subtype_evidence.csv", index=False)
    report = {
        "status": "passed",
        "scope": "Kalimantan incident reports with explicit positive vehicle counts; official sources preferred, attributable news retained separately",
        "incident_records": int(len(frame)),
        "provinces": frame["province"].value_counts().to_dict(),
        "official_or_primary_records": int((~frame["source_kind"].eq("news_web_article")).sum()),
        "news_records": int(frame["source_kind"].eq("news_web_article").sum()),
        "records_with_exact_personnel_total": int(frame["personnel_total"].notna().sum()),
        "records_with_personnel_lower_bound": int(frame["personnel_known_lower_bound"].notna().sum()),
        "fire_engine_positive_records": int(frame["fire_engine_count_explicit_positive"].notna().sum()),
        "water_tanker_positive_records": int(frame["water_tanker_count_explicit_positive"].notna().sum()),
        "pickup_positive_records": int(frame["pickup_count_explicit_positive"].notna().sum()),
        "rules": [
            "Null vehicle subtype means not reported; it is never a zero label.",
            "personnel_total is populated only when the source accounts for all listed groups; lower-bound personnel remains separate.",
            "This register is not merged into the Kalteng 2018–2019 calibration cohort.",
            "News reports are provenance-preserved support evidence, not a replacement for an official primary report.",
        ],
    }
    (OUTPUT_DIR / "feature2_vehicle_subtype_evidence_quality.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
